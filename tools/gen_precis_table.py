"""Generate ``turnkit/_precis_table.py`` from IANA's PRECIS derived-property registry.

Usage: ``python tools/gen_precis_table.py precis-tables-6.3.0.xml``

Fetch the registry file yourself, raw, from
``https://www.iana.org/assignments/precis-tables-6.3.0/precis-tables-6.3.0.xml`` (the
undated ``precis-tables`` URL is a redirect to it). Registry data is CC0 under IANA's
licensing terms. The generator records the file's sha256 and the registry's own
``updated`` date in the output, merges adjacent records of the same property, and refuses
a file with overlapping or unsorted ranges. It uses the standard library only.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys
import xml.etree.ElementTree as ET

NS = "{http://www.iana.org/assignments}"
URL = "https://www.iana.org/assignments/precis-tables-6.3.0/precis-tables-6.3.0.xml"
CODE = {
    "PVALID": "P",
    "ID_DIS or FREE_PVAL": "F",
    "CONTEXTJ": "J",
    "CONTEXTO": "O",
    "DISALLOWED": "D",
    "UNASSIGNED": "U",
}


def main(path: str) -> None:
    raw = pathlib.Path(path).read_bytes()
    root = ET.fromstring(raw)  # noqa: S314 - a file the operator fetched, no DTD handling needed
    updated = root.findtext(f"{NS}updated")
    rows: list[tuple[int, int, str]] = []
    for record in root.iter(f"{NS}record"):
        span = (record.findtext(f"{NS}codepoint") or "").strip()
        low, _, high = span.partition("-")
        start, end = int(low, 16), int(high or low, 16)
        rows.append((start, end, CODE[(record.findtext(f"{NS}property") or "").strip()]))
    merged: list[list[int | str]] = []
    expected = 0
    for start, end, code in rows:
        if start != expected:
            raise SystemExit(f"gap or overlap at U+{start:04X}, expected U+{expected:04X}")
        expected = end + 1
        if merged and merged[-1][2] == code:
            merged[-1][1] = end
        else:
            merged.append([start, end, code])
    if expected != 0x110000:
        raise SystemExit(f"the table stops at U+{expected - 1:04X}, not U+10FFFF")
    lines = [
        '"""PRECIS derived property values for Unicode 6.3.0 (generated; do not edit).',
        "",
        f"Source: {URL}",
        f"Registry updated: {updated}. Licence: CC0 (IANA registry terms).",
        "Generated by tools/gen_precis_table.py, which merges adjacent records of one property.",
        "Codes: P PVALID, F ID_DIS or FREE_PVAL, J CONTEXTJ, O CONTEXTO, D DISALLOWED,",
        "U UNASSIGNED (assigned after Unicode 6.3.0 counts as unassigned here).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'SOURCE_URL = "{URL}"',
        f'SOURCE_SHA256 = "{hashlib.sha256(raw).hexdigest()}"',
        f'SOURCE_UPDATED = "{updated}"',
        'UNICODE_VERSION = "6.3.0"',
        "",
        "# (first code point, last code point, property code), sorted and contiguous over 0..10FFFF",
        "RANGES: tuple[tuple[int, int, str], ...] = (",
    ]
    lines += [f'    (0x{a:04X}, 0x{b:04X}, "{c}"),' for a, b, c in merged]
    lines.append(")")
    out = pathlib.Path(__file__).resolve().parents[1] / "turnkit" / "_precis_table.py"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} records -> {len(merged)} ranges, sha256 {hashlib.sha256(raw).hexdigest()}")


if __name__ == "__main__":
    main(sys.argv[1])
